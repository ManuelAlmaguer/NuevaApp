// ---------------------------------------------------------------------------
// Signing configuration
// ---------------------------------------------------------------------------
// Credentials are read from (in order of precedence):
//   1. keystore.properties  (local, git-ignored  -> never committed)
//   2. Environment variables (used by GitHub Actions secrets)
// ---------------------------------------------------------------------------
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) {
        FileInputStream(keystorePropsFile).use { load(it) }
    }
}

fun signingValue(key: String, envName: String): String? =
    keystoreProps.getProperty(key)?.takeIf { it.isNotBlank() }
        ?: System.getenv(envName)?.takeIf { it.isNotBlank() }

